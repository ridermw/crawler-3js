#!/usr/bin/env python3
"""Bake the side masses of the crypt from the reference depth into src/heightfield.js.

The clay-sharpened reference depth (refdepth.py --mode guided) is projected to world points
through the fitted camera, binned to 0.5 m cells (80th percentile height), restricted to the two
side bands of the room, holes filled from neighbours, quantised to 5 cm and written as a compact
JS module. world.js stacks stone blocks to these heights (scaled by LAYOUT.hScale).

    python3 tools/fidelity/refdepth.py --mode guided --out /tmp/refg.npy
    python3 tools/fidelity/heightfield.py /tmp/refg.npy
"""
import sys
from pathlib import Path
import numpy as np
sys.path.insert(0, str(Path(__file__).parent))
from plan import plan, X0, Z0

ROOT = Path(__file__).resolve().parents[2]
CELL, XMIN, XMAX, ZMIN, ZMAX = 0.5, 7.0, 15.0, -7.5, 14.0


def main():
    g = plan(np.load(sys.argv[1]).astype(float))
    C = int(CELL / 0.1)
    nz, nx = g.shape[0] // C, g.shape[1] // C
    H = np.full((nz, nx), np.nan)
    for j in range(nz):
        for i in range(nx):
            b = g[j * C:(j + 1) * C, i * C:(i + 1) * C]; b = b[~np.isnan(b)]
            if len(b) >= 3: H[j, i] = np.percentile(b, 80)
    xs = X0 + (np.arange(nx) + 0.5) * CELL; zs = Z0 + (np.arange(nz) + 0.5) * CELL
    out = {}
    for sx, name in ((-1, "left"), (1, "right")):
        ci = [i for i in range(nx) if XMIN <= sx * xs[i] <= XMAX]
        ci = sorted(ci, key=lambda i: sx * xs[i])
        rj = [j for j in range(nz) if ZMIN <= zs[j] <= ZMAX]
        A = H[np.ix_(rj, ci)]
        for _ in range(6):  # fill holes from 4-neighbours
            m = np.isnan(A)
            if not m.any(): break
            P = np.pad(A, 1, constant_values=np.nan)
            nb = np.stack([P[:-2, 1:-1], P[2:, 1:-1], P[1:-1, :-2], P[1:-1, 2:]])
            fill = np.nanmean(np.where(np.isnan(nb), np.nan, nb), 0)
            A[m] = fill[m]
        A = np.nan_to_num(np.clip(A, 0, 7), nan=0.0)
        out[name] = {"x0": float(sx * xs[ci[0]]), "z0": float(zs[rj[0]]), "rows": [[int(round(v * 20)) for v in row] for row in A]}
    js = ["// Generated by tools/fidelity/heightfield.py from the reference depth pass: heights (in 5 cm",
          "// units) of the side masses on a 0.5 m grid. rows run along +z from z0; columns run outward",
          "// from x0 (away from the walkway).",
          "export const SIDE_HEIGHTS = {", f"  cell: {CELL},"]
    for name, d in out.items():
        rows = ",\n".join("      [" + ",".join(str(v) for v in r) + "]" for r in d["rows"])
        js.append(f"  {name}: {{ x0: {d['x0']}, z0: {d['z0']}, rows: [\n{rows}] }},")
    js.append("};")
    (ROOT / "src/heightfield.js").write_text("\n".join(js) + "\n")
    print("wrote src/heightfield.js", {k: (len(v['rows']), len(v['rows'][0])) for k, v in out.items()})


if __name__ == "__main__":
    main()
